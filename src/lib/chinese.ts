export function chineseText<T extends ReactNode>(value: T): T | string {
  if (typeof value !== 'string') return value
  if (labels[value]) return labels[value]
  if (value.includes(' · ')) return value.split(' · ').map(part => chineseText(part)).join('・')
  return value.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2}), (\d{4})\b/g, (_, month: string, day: string, year: string) => {
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
    return year + '年' + (months.indexOf(month) + 1) + '月' + day + '日'
  }).replace(/\b(\d+) min\b/g, '$1 分鐘')
}
