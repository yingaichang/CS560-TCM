const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { publish, allowed } = require('./auto-publish.cjs')
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'tcm-publish-test-'))
const root = path.join(temporary, 'working')
const remote = path.join(temporary, 'remote.git')
function git(cwd, ...args) { return execFileSync('git', args, { cwd, encoding: 'utf8', windowsHide: true }).trim() }
try {
  fs.mkdirSync(root)
  git(temporary, 'init', '--bare', remote)
  git(root, 'init', '-b', 'main')
  git(root, 'config', 'user.name', 'Deployment test')
  git(root, 'config', 'user.email', 'deployment-test@example.invalid')
  git(root, 'remote', 'add', 'origin', remote)
  fs.mkdirSync(path.join(root, 'src'))
  fs.writeFileSync(path.join(root, 'src/page.tsx'), 'initial\n')
  fs.writeFileSync(path.join(root, '.gitignore'), '.env.local\ncse03-ssh-YingAi/\n.local-deploy/\n')
  git(root, 'add', '.')
  git(root, 'commit', '-m', 'initial')
  git(root, 'push', '-u', 'origin', 'main')
  fs.writeFileSync(path.join(root, '.env.local'), 'private test configuration')
  fs.writeFileSync(path.join(root, 'src/page.tsx'), 'saved website change\n')
  publish(root)
  assert.equal(git(root, 'rev-parse', 'HEAD'), git(temporary, '--git-dir', remote, 'rev-parse', 'main'))
  assert.equal(git(root, 'ls-files', '.env.local'), '')
  fs.renameSync(path.join(root, 'src/page.tsx'), path.join(root, 'src/home.tsx'))
  publish(root)
  assert.equal(git(root, 'ls-files', 'src/page.tsx'), '')
  assert.equal(git(root, 'ls-files', 'src/home.tsx'), 'src/home.tsx')
  git(root, 'mv', 'src/home.tsx', 'src/final.tsx')
  publish(root)
  assert.equal(git(root, 'ls-files', 'src/final.tsx'), 'src/final.tsx')
  const before = git(root, 'rev-parse', 'HEAD')
  fs.writeFileSync(path.join(root, 'src/credential.ts'), 'sk_' + 'test_' + 'A'.repeat(32))
  assert.throws(() => publish(root), /Possible credential/)
  assert.equal(git(root, 'rev-parse', 'HEAD'), before)
  fs.unlinkSync(path.join(root, 'src/credential.ts'))
  fs.writeFileSync(path.join(root, 'private-notes.txt'), 'outside website scope')
  git(root, 'add', 'private-notes.txt')
  assert.throws(() => publish(root), /outside website scope/)
  for (const file of ['.env.local', 'prisma/dev.db', 'cse03-ssh-YingAi/cse03', 'prisma/schema.production.prisma']) assert.equal(allowed(file), false)
  console.log('PASS: real commit/push to isolated Git remote, saved edits, deletions, staged renames, ignored environment, credential rejection and scope enforcement.')
} finally {
  assert.ok(path.resolve(temporary).startsWith(path.resolve(os.tmpdir()) + path.sep + 'tcm-publish-test-'))
  fs.rmSync(temporary, { recursive: true, force: true })
}
